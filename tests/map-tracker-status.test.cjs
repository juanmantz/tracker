const {readFileSync}=require('fs');
const vm=require('vm');
const assert=require('assert/strict');
const source=readFileSync(__dirname+'/../integrations/dreams/map-tracker-status.js','utf8');
const sandbox={};vm.createContext(sandbox);vm.runInContext(source,sandbox);
const now=1792332000;
const note=d=>({kind:'note',archived:true,fields:{notes:JSON.stringify({schema:'dreamstime/review/v1',device:'mac',updated_at:now,sensor:{accessibility:true},...d})}});
const status=nodes=>sandbox.dreamsTimeMapStatus({nodes},now);
assert.equal(status([]),null);
const d=note({last_save:{week:'2026-10-12',seconds:748.399,unassigned_seconds:58062.52}});
let s=status([d]);assert.equal(s.label,'Most activity has no project');assert.equal(s.published,0);assert.equal(s.matched,1);assert.equal(s.assigned,748.399);
assert.equal(status([note({updated_at:now-7200,sensor:{accessibility:false,collector:{ax_trusted:false}}})]).label,'Last report received');
assert.equal(status([note({sensor:{accessibility:false,collector:{ax_trusted:false}}})]).label,'Project detection needs access');
assert.equal(status([note({updated_at:now+500})]),null);
assert.equal(status([note({paused:true})]).label,'Paused');
assert.equal(status([note({sync_error:'revoked'})]).label,'Transfer needs attention');
assert.equal(status([note({publication:{week:'2026-10-12',seconds:100,unassigned_seconds:500},last_save:{week:'2026-10-05',seconds:9999,unassigned_seconds:0}})]).assigned,100);
assert.equal(status([note({last_save:{week:'2026-10-12',seconds:'6000',unassigned_seconds:0}})]).hasTotals,false);
const active={kind:'service',measurements:[{metric:'workedHours',basis:'Worked',source:'Dreams Time · mac',period:{start:'2026-10-12'},amount:{value:1,unit:'hours'}}]};
assert.equal(status([d,active]).published,1);
assert.equal(status([d,{...active,archived:true}]).published,0);
assert.equal(status([d,{kind:'service',measurements:[{...active.measurements[0],source:'Manual'}]}]).published,0);
assert.equal(status([d,note({updated_at:now-10,last_save:{week:'2026-10-12',seconds:9999,unassigned_seconds:0}})]).assigned,748.399);
assert.equal(sandbox.dreamsTimeDuration(58062.52),'16h 7m');
console.log('14 tracker status checks passed');
